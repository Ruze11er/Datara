// Helpers for the Academy case dataset generators (scripts/case-data/*.mjs).

/** Seeded pseudo-random numbers (mulberry32). Each dataset gets its own stream, so they never affect each other. */
export function makeRandom(startSeed) {
  let seed = startSeed
  const rand = () => {
    seed |= 0
    seed = (seed + 0x6d2b79f5) | 0
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
  const randInt = (min, max) => min + Math.floor(rand() * (max - min + 1))
  const pick = (list) => list[Math.floor(rand() * list.length)]
  /** pairs: [[value, weight], ...] */
  const weighted = (pairs) => {
    const total = pairs.reduce((s, [, w]) => s + w, 0)
    let r = rand() * total
    for (const [value, w] of pairs) if ((r -= w) < 0) return value
    return pairs[pairs.length - 1][0]
  }
  const shuffle = (list) => {
    const out = [...list]
    for (let i = out.length - 1; i > 0; i--) {
      const j = Math.floor(rand() * (i + 1))
      ;[out[i], out[j]] = [out[j], out[i]]
    }
    return out
  }
  /**
   * Like `weighted`, but with far less random drift: each value is chosen in proportion to its weight over any
   * stretch of picks (a smooth weighted round-robin with random jitter, so the sequence still looks random).
   * Used for the mixes a case's story depends on, so that small segments don't swing by chance.
   * The returned function takes an optional Set of values to skip (e.g. products already in the order).
   */
  const balanced = (pairs) => {
    const total = pairs.reduce((s, [, w]) => s + w, 0)
    const items = pairs.map(([value, weight]) => ({ value, weight, current: rand() * weight }))
    return (skip) => {
      for (const it of items) it.current += it.weight * (0.6 + 0.8 * rand())
      let best = null
      for (const it of items) if (!skip?.has(it.value) && (best === null || it.current > best.current)) best = it
      best.current -= total
      return best.value
    }
  }
  return { rand, randInt, pick, weighted, shuffle, balanced }
}

const DAY = 86_400_000
export const dateMs = (iso) => Date.parse(`${iso.slice(0, 10)}T00:00:00Z`)
export const toDate = (ms) => new Date(ms).toISOString().slice(0, 10)
export const addDays = (iso, days) => toDate(dateMs(iso) + days * DAY)

/** Every date from `from` to `to`, inclusive (YYYY-MM-DD). */
export function dateRange(from, to) {
  const days = []
  for (let d = from; d <= to; d = addDays(d, 1)) days.push(d)
  return days
}

/** "2025-08-12" + seconds since midnight -> "2025-08-12 14:03:22" */
export function timestamp(date, seconds) {
  const hh = String(Math.floor(seconds / 3600)).padStart(2, '0')
  const mm = String(Math.floor((seconds % 3600) / 60)).padStart(2, '0')
  const ss = String(seconds % 60).padStart(2, '0')
  return `${date} ${hh}:${mm}:${ss}`
}

export const round2 = (n) => Math.round(n * 100) / 100

const sqlValue = (v) =>
  v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`

function insert(table, rows) {
  if (rows.length === 0) return ''
  const columns = Object.keys(rows[0])
  // Several INSERT statements of 500 rows keep each statement a reasonable size.
  const parts = []
  for (let i = 0; i < rows.length; i += 500) {
    parts.push(
      `INSERT INTO ${table} (${columns.join(', ')}) VALUES\n` +
        rows
          .slice(i, i + 500)
          .map((r) => `  (${columns.map((c) => sqlValue(r[c])).join(', ')})`)
          .join(',\n') +
        ';\n'
    )
  }
  return parts.join('')
}

/** tables: [{ name, create (CREATE TABLE statement), rows }] */
export function toSql(title, tables) {
  return (
    `-- ${title}\n-- Generated by scripts/generate-case-data.mjs. Do not edit by hand.\n\n` +
    tables.map((t) => `${t.create.trim()}\n`).join('\n') +
    '\n' +
    tables.map((t) => insert(t.name, t.rows)).join('\n')
  )
}
